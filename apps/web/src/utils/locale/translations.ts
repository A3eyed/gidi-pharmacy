export const RTL_LANGUAGES = new Set(LANGUAGES.filter((l) => l.rtl).map((l) => l.code));

export function getBundle(language: string): Bundle {
  return BUNDLES[language] ?? en;
}

/** Look up a key with optional {placeholder} interpolation. */
export function translate(
  language: string,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const bundle = getBundle(language);
  let value = bundle[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}

export function languageName(code: string) {
  return LANGUAGES.find((l) => l.code === code)?.native ?? code;
}
